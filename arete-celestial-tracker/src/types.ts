export interface User {
  id: string;
  email: string;
  username: string;
  status: 'pending' | 'approved';
  timezone: string;
  createdAt: string;
}

export interface WelcomeContext {
  streak: number;
  latestSummary: {
    type: 'weekly' | 'monthly';
    text: string;
    rangeEnd: string;
  } | null;
  hasGoals: boolean;
  lastLogDate: string | null;
  welcomeMessage: string;
}

export interface FoodMacros {
  proteinG?: number;
  carbsG?: number;
  fatsG?: number;
  fiberG?: number;
  vitaminC?: string;
  vitaminD?: string;
  iron?: string;
  calcium?: string;
  potassium?: string;
  magnesium?: string;
}

export interface FoodEntry {
  description: string;
  macros?: FoodMacros;
  macroSummary?: string;
}

export interface WaterEntry {
  amountMl: number;
  note?: string;
}

export interface WorkoutSession {
  label: string;
  durationMin?: number;
}

export interface WorkoutEntry {
  didSession: boolean;
  sessions?: WorkoutSession[];
}

export interface SleepEntry {
  mainSleepHours?: number;
  napHours?: number;
  sleepQuality?: number;
  notes?: string;
}

export interface ReadingEntry {
  didRead: boolean;
  pages?: number;
  title?: string;
  note?: string;
}

export interface CodingEntry {
  summary: string;
}

export interface StructuredDay {
  food?: FoodEntry;
  water?: WaterEntry;
  workout?: WorkoutEntry;
  sleep?: SleepEntry;
  reading?: ReadingEntry;
  codingBuilding?: CodingEntry | string;
  productivityScore?: number;
  habitsScore?: number;
  screenTimeMinutes?: number;
}

export interface EnergyEstimate {
  caloriesInEstimate: number | null;
  caloriesOutWorkoutEstimate: number | null;
  confidence: 'low' | 'medium' | 'high';
  rationale: string;
  sources: { title: string; url?: string }[];
  model: string;
  updatedAt: string;
}

export interface DailyEntry {
  _id: string;
  userId: string;
  dateKey: string;
  timezoneAtEntry?: string;
  rawMessage: string;
  structured: StructuredDay;
  dailySummary: string;
  ingestModel?: string;
  energyEstimate?: EnergyEstimate;
  createdAt: string;
  updatedAt: string;
}

export interface GoalTargets {
  workoutsPerWeek?: number;
  readingPagesPerWeek?: number;
  targetWaterMlPerDay?: number;
  codingHoursPerWeek?: number;
}

export interface UserGoals {
  targets: GoalTargets;
  notes: string | null;
  updatedAt: string | null;
}

export interface CoachConversation {
  _id: string;
  userId: string;
  title: string;
  titleAutoGenerated: boolean | null;
  messageCount: number;
  createdAt: string;
  updatedAt: string;
  deletedAt: string | null;
}

export interface CoachMessage {
  _id: string;
  conversationId: string;
  userId: string;
  role: 'user' | 'assistant';
  content: string;
  timestamp: string;
}
