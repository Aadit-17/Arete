import { NextRequest, NextResponse } from "next/server";
import { ObjectId } from "mongodb";
import { getDb } from "@/lib/db";
import { requireApprovedUser, apiError } from "@/lib/middleware";
import type { CoachConversationDoc } from "@/lib/types";

type Params = { params: Promise<{ id: string }> };

// ---------------------------------------------------------------------------
// GET  /api/coach/conversations/:id   — fetch single conversation
// PATCH /api/coach/conversations/:id  — rename title
// DELETE /api/coach/conversations/:id — soft delete
// ---------------------------------------------------------------------------

export async function GET(req: NextRequest, { params }: Params) {
    const auth = await requireApprovedUser(req);
    if (auth instanceof NextResponse) return auth;

    const { id } = await params;

    let convId: ObjectId;
    try { convId = new ObjectId(id); } catch { return apiError("Invalid conversation id", 400); }

    const db = await getDb();
    const doc = await db
        .collection<CoachConversationDoc>("coach_conversations")
        .findOne({ _id: convId, userId: auth.userId, deletedAt: null });

    if (!doc) return apiError("Conversation not found", 404);

    return NextResponse.json({
        ...doc,
        _id: doc._id?.toString(),
        userId: doc.userId?.toString(),
    });
}

export async function PATCH(req: NextRequest, { params }: Params) {
    const auth = await requireApprovedUser(req);
    if (auth instanceof NextResponse) return auth;

    const { id } = await params;

    let convId: ObjectId;
    try { convId = new ObjectId(id); } catch { return apiError("Invalid conversation id", 400); }

    let body: unknown;
    try { body = await req.json(); } catch { return apiError("Invalid JSON body", 400); }

    const { title } = body as Record<string, unknown>;
    if (typeof title !== "string" || !title.trim()) return apiError("title string required", 400);

    const db = await getDb();
    const result = await db
        .collection<CoachConversationDoc>("coach_conversations")
        .updateOne(
            { _id: convId, userId: auth.userId, deletedAt: null },
            { $set: { title: title.trim(), titleAutoGenerated: false, updatedAt: new Date() } }
        );

    if (result.matchedCount === 0) return apiError("Conversation not found", 404);
    return NextResponse.json({ success: true });
}

export async function DELETE(req: NextRequest, { params }: Params) {
    const auth = await requireApprovedUser(req);
    if (auth instanceof NextResponse) return auth;

    const { id } = await params;

    let convId: ObjectId;
    try { convId = new ObjectId(id); } catch { return apiError("Invalid conversation id", 400); }

    const db = await getDb();
    const result = await db
        .collection<CoachConversationDoc>("coach_conversations")
        .updateOne(
            { _id: convId, userId: auth.userId, deletedAt: null },
            { $set: { deletedAt: new Date(), updatedAt: new Date() } }
        );

    if (result.matchedCount === 0) return apiError("Conversation not found", 404);
    return NextResponse.json({ success: true });
}
