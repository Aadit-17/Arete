import { NextRequest, NextResponse } from "next/server";
import { getDb } from "@/lib/db";
import { requireApprovedUser, apiError } from "@/lib/middleware";
import { serializeCoachConversationPublic } from "@/lib/serialize-public";
import type { CoachConversationDoc } from "@/lib/types";

// ---------------------------------------------------------------------------
// GET  /api/coach/conversations  — paged list (updatedAt desc)
// POST /api/coach/conversations  — create new conversation
// ---------------------------------------------------------------------------

export async function GET(req: NextRequest) {
    const auth = await requireApprovedUser(req);
    if (auth instanceof NextResponse) return auth;

    const { searchParams } = new URL(req.url);
    const page = Math.max(1, parseInt(searchParams.get("page") ?? "1", 10));
    const limit = Math.min(50, parseInt(searchParams.get("limit") ?? "20", 10));
    const search = searchParams.get("search") ?? "";
    const skip = (page - 1) * limit;

    const db = await getDb();
    const col = db.collection<CoachConversationDoc>("coach_conversations");

    const filter: Record<string, unknown> = {
        userId: auth.userId,
        deletedAt: null,   // exclude soft-deleted
    };
    if (search) filter.title = { $regex: search, $options: "i" };

    const [docs, total] = await Promise.all([
        col.find(filter).sort({ updatedAt: -1 }).skip(skip).limit(limit).toArray(),
        col.countDocuments(filter),
    ]);

    const total_pages = Math.ceil(total / limit);

    return NextResponse.json({
        conversations: docs.map(serializeCoachConversationPublic),
        page,
        limit,
        total,
        total_pages,
        has_next: page < total_pages,
        has_previous: page > 1,
    });
}

export async function POST(req: NextRequest) {
    const auth = await requireApprovedUser(req);
    if (auth instanceof NextResponse) return auth;

    let title = "New conversation";
    try {
        const body = await req.json();
        if (typeof body?.title === "string" && body.title.trim()) {
            title = body.title.trim();
        }
    } catch {
        // body optional
    }

    const now = new Date();
    const doc: CoachConversationDoc = {
        userId: auth.userId,
        title,
        titleAutoGenerated: null,
        messageCount: 0,
        createdAt: now,
        updatedAt: now,
        deletedAt: null,
    };

    const db = await getDb();
    const result = await db.collection<CoachConversationDoc>("coach_conversations").insertOne(doc);

    return NextResponse.json(
        { id: result.insertedId.toString(), title, createdAt: now },
        { status: 201 }
    );
}

