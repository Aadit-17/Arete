import type {
    CoachConversationDoc,
    CoachMessageDoc,
    DailyEntryDoc,
    EnergyEstimate,
    PeriodSummaryDoc,
} from "@/lib/types";

export type PublicEnergyEstimate = Pick<
    EnergyEstimate,
    'caloriesInEstimate' | 'caloriesOutWorkoutEstimate' | 'confidence' | 'rationale'
>;

/** Strip internal LLM metadata from energy payloads sent to the client. */
export function publicEnergyEstimate(e: EnergyEstimate | undefined): PublicEnergyEstimate | undefined {
    if (!e) return undefined;
    return {
        caloriesInEstimate: e.caloriesInEstimate,
        caloriesOutWorkoutEstimate: e.caloriesOutWorkoutEstimate,
        confidence: e.confidence,
        rationale: e.rationale,
    };
}

export function serializeDailyEntryPublic(e: DailyEntryDoc) {
    return {
        _id: e._id?.toString(),
        dateKey: e.dateKey,
        timezoneAtEntry: e.timezoneAtEntry,
        rawMessage: e.rawMessage,
        structured: e.structured,
        dailySummary: e.dailySummary,
        energyEstimate: publicEnergyEstimate(e.energyEstimate),
        createdAt: e.createdAt,
        updatedAt: e.updatedAt,
    };
}

export function serializePeriodSummaryPublic(d: PeriodSummaryDoc) {
    return {
        _id: d._id?.toString(),
        periodType: d.periodType,
        rangeStart: d.rangeStart,
        rangeEnd: d.rangeEnd,
        title: d.title,
        summaryText: d.summaryText,
        stats: d.stats,
        createdAt: d.createdAt,
    };
}

export function serializeCoachConversationPublic(d: CoachConversationDoc) {
    return {
        _id: d._id?.toString(),
        title: d.title,
        titleAutoGenerated: d.titleAutoGenerated ?? null,
        messageCount: d.messageCount ?? 0,
        createdAt: d.createdAt,
        updatedAt: d.updatedAt,
    };
}

export function serializeCoachMessagePublic(m: CoachMessageDoc) {
    return {
        _id: m._id?.toString(),
        conversationId: m.conversationId?.toString(),
        role: m.role,
        content: m.content,
        timestamp: m.timestamp,
    };
}
