import { ObjectId } from "mongodb";

// ---------------------------------------------------------------------------
// users
// ---------------------------------------------------------------------------

export interface UserDoc {
    _id?: ObjectId;
    email: string;         // lowercase, unique
    username: string;      // unique
    passwordHash: string;
    status: "pending" | "approved";
    timezone: string;      // IANA, e.g. "Asia/Kolkata"
    createdAt: Date;
    updatedAt: Date;
}

// ---------------------------------------------------------------------------
// energy_estimates
// ---------------------------------------------------------------------------

export interface EnergyEstimateSource {
    title: string;
    url?: string;
}

export interface EnergyEstimate {
    caloriesInEstimate: number | null;
    caloriesOutWorkoutEstimate: number | null;
    confidence: "low" | "medium" | "high";
    rationale: string;
    sources: EnergyEstimateSource[];
    model: string;
    updatedAt: string;
}

// ---------------------------------------------------------------------------
// daily_entries
// ---------------------------------------------------------------------------

export interface FoodMacros {
    proteinG?: number;
    carbsG?: number;
    fatsG?: number;
    fiberG?: number;
    vitaminC?: string;     // presence/amount description
    vitaminD?: string;
    iron?: string;
    calcium?: string;
    potassium?: string;
    magnesium?: string;
}

export interface FoodEntry {
    description: string;
    macros?: FoodMacros;
    macroSummary?: string;  // 1 sentence summary of macros and what's needed
}

export interface WaterEntry {
    amountMl: number;
    note?: string;
}

export interface WorkoutSession {
    label: string;
    durationMin?: number;
}

export interface WorkoutEntry {
    didSession: boolean;
    sessions?: WorkoutSession[];
}

export interface ReadingEntry {
    didRead: boolean;
    pages?: number;
    title?: string;
    note?: string;
}

export interface CodingEntry {
    summary: string;
}

export interface SleepEntry {
    mainSleepHours?: number;     // Normal night sleep in hours
    napHours?: number;            // Total nap time in hours
    sleepQuality?: number;         // 1–10 subjective quality
    notes?: string;
}

export interface StructuredDay {
    food?: FoodEntry;
    water?: WaterEntry;
    workout?: WorkoutEntry;
    sleep?: SleepEntry;
    productivityScore?: number;  // 0–10
    reading?: ReadingEntry;
    codingBuilding?: CodingEntry | string;
    habitsScore?: number;        // 0–10
    screenTimeMinutes?: number;  // Total screen time in minutes
}

export interface DailyEntryDoc {
    _id?: ObjectId;
    userId: ObjectId;
    dateKey: string;            // YYYY-MM-DD (from UI picker)
    timezoneAtEntry?: string;
    rawMessage: string;
    structured: StructuredDay;
    dailySummary: string;
    ingestModel?: string;
    energyEstimate?: EnergyEstimate;
    createdAt: Date;
    updatedAt: Date;
}

// ---------------------------------------------------------------------------
// user_goals
// ---------------------------------------------------------------------------

export interface GoalTargets {
    workoutsPerWeek?: number;
    readingPagesPerWeek?: number;
    targetWaterMlPerDay?: number;
    codingHoursPerWeek?: number;
}

export interface UserGoalsDoc {
    _id?: ObjectId;
    userId: ObjectId;
    targets: GoalTargets;
    notes?: string;
    updatedAt: Date;
}

// ---------------------------------------------------------------------------
// period_summaries
// ---------------------------------------------------------------------------

export interface PeriodSummaryDoc {
    _id?: ObjectId;
    userId: ObjectId;
    periodType: "weekly" | "monthly";
    rangeStart: string;   // YYYY-MM-DD inclusive
    rangeEnd: string;     // YYYY-MM-DD inclusive
    title?: string;
    summaryText: string;
    stats?: Record<string, unknown>;
    model?: string;
    createdAt: Date;
}

// ---------------------------------------------------------------------------
// user_progress
// ---------------------------------------------------------------------------

export interface UserProgressDoc {
    _id?: ObjectId;
    userId: ObjectId;
    narrative: string;
    lastRefreshedAt: Date;
    updatedAt: Date;
}

// ---------------------------------------------------------------------------
// coach_conversations
// ---------------------------------------------------------------------------

export interface CoachConversationDoc {
    _id?: ObjectId;
    userId: ObjectId;
    title: string;
    titleAutoGenerated?: boolean | null;
    messageCount?: number;
    createdAt: Date;
    updatedAt: Date;
    deletedAt?: Date | null;
}

// ---------------------------------------------------------------------------
// coach_messages
// ---------------------------------------------------------------------------

export interface CoachMessageDoc {
    _id?: ObjectId;
    conversationId: ObjectId;
    userId: ObjectId;
    role: "user" | "assistant";
    content: string;
    timestamp: Date;
}

// ---------------------------------------------------------------------------
// refresh_tokens
// ---------------------------------------------------------------------------

export interface RefreshTokenDoc {
    _id?: ObjectId;
    userId: ObjectId;
    tokenHash: string;
    expiresAt: Date;
    createdAt: Date;
    revokedAt?: Date | null;
}
